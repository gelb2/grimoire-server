// ── 메인 실행 ──────────────────────────────────────────

async function main() {
  console.log('=== 추가 고전문학 시드 스크립트 시작 ===')
  console.log(`DATABASE_URL: ${process.env.DATABASE_URL?.substring(0, 30)}...`)

  const totalWorks = AUTHORS.reduce((sum, a) => sum + a.works.length, 0)
  console.log(`작가 수: ${AUTHORS.length} (신규: ${AUTHORS.filter(a => a.isNew).length})`)
  console.log(`추가 작품 수: ${totalWorks}`)
  console.log()

  let authorSuccess = 0
  let workSuccess = 0
  let workSkipped = 0
  let episodeSuccess = 0
  let errors: string[] = []

  for (const authorDef of AUTHORS) {
    console.log(`\n[작가] ${authorDef.name} (${authorDef.slug}) ${authorDef.isNew ? '★ 신규' : '기존'}`)

    // 1. 작가 찾기 또는 생성
    let author = await prisma.author.findUnique({ where: { slug: authorDef.slug } })

    if (!author && authorDef.isNew) {
      // 신규 작가 생성
      const passwordHash = await bcrypt.hash(authorDef.password, 10)
      author = await prisma.author.create({
        data: {
          slug: authorDef.slug,
          name: authorDef.name,
          email: authorDef.email,
          passwordHash,
          credits: 3,
        },
      })
      console.log(`  -> 신규 작가 생성 완료 (id: ${author.id})`)
    } else if (!author) {
      // 기존 작가인데 DB에 없는 경우 — 생성
      const passwordHash = await bcrypt.hash(authorDef.password, 10)
      author = await prisma.author.create({
        data: {
          slug: authorDef.slug,
          name: authorDef.name,
          email: authorDef.email,
          passwordHash,
          credits: 3,
        },
      })
      console.log(`  -> 기존 작가 DB 부재, 새로 생성 (id: ${author.id})`)
    } else {
      console.log(`  -> 기존 작가 확인 (id: ${author.id})`)
    }
    authorSuccess++

    // 2. 각 작품 생성 + 에피소드
    for (const workDef of authorDef.works) {
      // 이미 존재하는 작품인지 확인
      const existingWork = await prisma.work.findUnique({
        where: { authorId_slug: { authorId: author.id, slug: workDef.slug } },
      })

      if (existingWork) {
        console.log(`  [작품] ${workDef.title} — 이미 존재, 스킵`)
        workSkipped++
        continue
      }

      try {
        // 작품 생성
        const work = await prisma.work.create({
          data: {
            authorId: author.id,
            slug: workDef.slug,
            title: workDef.title,
            description: workDef.description,
          },
        })
        workSuccess++
        console.log(`  [작품] ${workDef.title} (${workDef.slug}) — 생성 완료`)

        // 에피소드 카운트 (기존 에피소드가 있을 수 있으므로)
        const episodeCount = await prisma.episode.count({ where: { workId: work.id } })

        // 블록 파싱
        const blocks = parseContentToBlocks(workDef.content)

        // 에피소드 생성
        const episodeSlug = workDef.slug
        const episode = await prisma.episode.create({
          data: {
            workId: work.id,
            slug: episodeSlug,
            title: workDef.title,
            orderNum: episodeCount + 1,
            blocks: JSON.parse(JSON.stringify(blocks)),
            rawMd: workDef.content,
            sourceFormat: 'markdown',
          },
        })
        episodeSuccess++
        console.log(`    -> 에피소드 생성 완료 (id: ${episode.id}, 블록 ${blocks.length}개)`)
      } catch (err: any) {
        errors.push(`${workDef.title}: ${err.message}`)
        console.error(`    !! 오류: ${err.message}`)
      }
    }
  }

  // 결과 요약
  console.log('\n========================================')
  console.log('=== 추가 고전문학 시드 결과 ===')
  console.log('========================================')
  console.log(`작가:    성공 ${authorSuccess} / 전체 ${AUTHORS.length}`)
  console.log(`작품:    성공 ${workSuccess} / 스킵(기존) ${workSkipped} / 전체 ${totalWorks}`)
  console.log(`에피소드: 성공 ${episodeSuccess} / 전체 ${totalWorks - workSkipped}`)
  if (errors.length > 0) {
    console.log(`오류:    ${errors.length}건`)
    for (const e of errors) console.log(`  - ${e}`)
  }
  console.log('========================================')
}

main()
  .catch((err) => {
    console.error('치명적 오류:', err)
    process.exit(1)
  })
  .finally(() => prisma.$disconnect())
